// MacKeyboardLayout is the current macOS keyboard layout.
type MacKeyboardLayout struct {
	id   string
	name string
}

// MacKeyboardMapper maps keystrokes through a layout's key equivalents.
type MacKeyboardMapper struct {
	keyEquivalents map[rune]rune
}

var (
	_ gpui.PlatformKeyboardLayout = (*MacKeyboardLayout)(nil)
	_ gpui.PlatformKeyboardMapper = (*MacKeyboardMapper)(nil)
)

// ID returns the input source identifier.
func (l *MacKeyboardLayout) ID() string {
	return l.id
}

// Name returns the localised input source name.
func (l *MacKeyboardLayout) Name() string {
	return l.name
}

// MapKeyEquivalent maps keystroke through the layout's key equivalents when useKeyEquivalents is set.
func (m *MacKeyboardMapper) MapKeyEquivalent(keystroke gpui.Keystroke, useKeyEquivalents bool) gpui.KeybindingKeystroke {
	if useKeyEquivalents && m.keyEquivalents != nil {
		if utf8.RuneCountInString(keystroke.Key) == 1 {
			r, _ := utf8.DecodeRuneInString(keystroke.Key)
			if key, ok := m.keyEquivalents[r]; ok {
				keystroke.Key = string(key)
			}
		}
	}
	return gpui.KeybindingKeystrokeFromKeystroke(keystroke)
}

// GetKeyEquivalents returns the layout's key equivalents, or nil when it has none.
func (m *MacKeyboardMapper) GetKeyEquivalents() map[rune]rune {
	return m.keyEquivalents
}

// NewMacKeyboardLayout reads the current keyboard layout input source.
func NewMacKeyboardLayout() *MacKeyboardLayout {
	mustLoadCarbon()
	currentKeyboard := tisCopyCurrentKeyboardLayoutInputSource()
	if currentKeyboard == 0 {
		return &MacKeyboardLayout{id: "", name: ""}
	}

	id := nsStringToStr(tisGetInputSourceProperty(currentKeyboard, kTISPropertyInputSourceID))
	name := nsStringToStr(tisGetInputSourceProperty(currentKeyboard, kTISPropertyLocalizedName))

	objc.Release(currentKeyboard)

	return &MacKeyboardLayout{id: id, name: name}
}

// NewMacKeyboardMapper returns the mapper for the layout with id layoutID.
func NewMacKeyboardMapper(layoutID string) *MacKeyboardMapper {
	keyEquivalents := getKeyEquivalents(layoutID)

	return &MacKeyboardMapper{keyEquivalents: keyEquivalents}
}

