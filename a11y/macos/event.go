//go:build darwin && !ios

package macos

import (
	"github.com/megascan/gpui-go/a11y"
	"github.com/megascan/gpui-go/a11y/consumer"
	"github.com/megascan/gpui-go/internal/apple/objc"
)

const (
	nsAccessibilityPriorityLow    objc.NSInteger = 10
	nsAccessibilityPriorityMedium objc.NSInteger = 50
	nsAccessibilityPriorityHigh   objc.NSInteger = 90
)

type queuedEvent interface {
	raise(context *Context)
}

type queuedEventGeneric struct {
	nodeID       consumer.NodeID
	notification string
}

type queuedEventNodeDestroyed struct {
	nodeID consumer.NodeID
}

type queuedEventAnnouncement struct {
	text     string
	priority objc.NSInteger
}

func liveRegionAnnouncement(node *consumer.Node) queuedEvent {
	text, ok := node.Value()
	if !ok {
		panic("called `Option::unwrap()` on a `None` value")
	}
	priority := nsAccessibilityPriorityMedium
	if node.Live() == a11y.LiveAssertive {
		priority = nsAccessibilityPriorityHigh
	}
	return queuedEventAnnouncement{text: text, priority: priority}
}

func (e queuedEventGeneric) raise(context *Context) {
	platformNode := context.getOrCreatePlatformNode(e.nodeID)
	accessibilityPostNotification(platformNode, axConst(e.notification))
}

func (e queuedEventNodeDestroyed) raise(context *Context) {
	if platformNode, ok := context.removePlatformNode(e.nodeID); ok {
		accessibilityPostNotification(platformNode, axConst("NSAccessibilityUIElementDestroyedNotification"))
		objc.Release(platformNode)
	}
}

func (e queuedEventAnnouncement) raise(context *Context) {
	view := context.view.load()
	if view == objc.Nil {
		return
	}
	defer objc.Release(view)
	window := objc.Send[objc.ID](view, objc.Sel("window"))
	if window == objc.Nil {
		return
	}
	objc.AutoreleasePool(func() {
		userInfo := objc.AllocInit(objc.GetClass("NSMutableDictionary"))
		defer objc.Release(userInfo)
		text := objc.NSStringFromGo(e.text)
		defer objc.Release(text)
		dictionarySet(userInfo, axConst("NSAccessibilityAnnouncementKey"), text)
		dictionarySet(userInfo, axConst("NSAccessibilityPriorityKey"), nsNumberWithInteger(e.priority))
		accessibilityPostNotificationWithUserInfo(window, axConst("NSAccessibilityAnnouncementRequestedNotification"), userInfo)
	})
}

// QueuedEvents are the events generated by a tree update.
type QueuedEvents struct {
	context *Context
	events  []queuedEvent
}

func newQueuedEvents(context *Context, events []queuedEvent) *QueuedEvents {
	return &QueuedEvents{context: context, events: events}
}

// Raise raises all queued events synchronously. No lock or borrow needed to reach the adapter may
// be held while it runs.
func (q *QueuedEvents) Raise() {
	for _, event := range q.events {
		event.raise(q.context)
	}
}

func focusEvent(nodeID consumer.NodeID) queuedEvent {
	return queuedEventGeneric{nodeID: nodeID, notification: "NSAccessibilityFocusedUIElementChangedNotification"}
}

type eventGenerator struct {
	context             *Context
	events              []queuedEvent
	textChanged         map[consumer.NodeID]struct{}
	selectedRowsChanged map[consumer.NodeID]struct{}
}

func newEventGenerator(context *Context) *eventGenerator {
	return &eventGenerator{
		context:             context,
		textChanged:         map[consumer.NodeID]struct{}{},
		selectedRowsChanged: map[consumer.NodeID]struct{}{},
	}
}

func (g *eventGenerator) intoResult() *QueuedEvents {
	return newQueuedEvents(g.context, g.events)
}

func (g *eventGenerator) removeSubtree(node *consumer.Node) {
	toRemove := []consumer.Node{*node}
	for len(toRemove) > 0 {
		node := toRemove[0]
		toRemove = toRemove[1:]
		for child := range node.FilteredChildren(filter).All() {
			toRemove = append(toRemove, child)
		}
		g.events = append(g.events, queuedEventNodeDestroyed{nodeID: node.ID()})
	}
}

func (g *eventGenerator) insertTextChangeIfNeededParent(node consumer.Node) {
	if !node.SupportsTextRanges() {
		return
	}
	id := node.ID()
	if _, ok := g.textChanged[id]; ok {
		return
	}
	g.events = append([]queuedEvent{queuedEventGeneric{nodeID: id, notification: "NSAccessibilityValueChangedNotification"}}, g.events...)
	g.textChanged[id] = struct{}{}
}

func (g *eventGenerator) insertTextChangeIfNeeded(node *consumer.Node) {
	if node.Role() != a11y.RoleTextRun {
		return
	}
	if parent, ok := node.FilteredParent(filter); ok {
		g.insertTextChangeIfNeededParent(parent)
	}
}

func (g *eventGenerator) enqueueSelectedRowsChangeIfNeededParent(node consumer.Node) {
	id := node.ID()
	if _, ok := g.selectedRowsChanged[id]; ok {
		return
	}
	g.events = append(g.events, queuedEventGeneric{nodeID: id, notification: "NSAccessibilitySelectedRowsChangedNotification"})
	g.selectedRowsChanged[id] = struct{}{}
}

func (g *eventGenerator) enqueueSelectedRowsChangeIfNeeded(node *consumer.Node) {
	if !(nodeWrapper{node}).isItemLike() {
		return
	}
	if container, ok := node.SelectionContainer(filter); ok {
		g.enqueueSelectedRowsChangeIfNeededParent(container)
	}
}

func (g *eventGenerator) NodeAdded(node *consumer.Node) {
	g.insertTextChangeIfNeeded(node)
	if filter(node) != consumer.FilterResultInclude {
		return
	}
	if selected, ok := node.IsSelected(); ok && selected {
		g.enqueueSelectedRowsChangeIfNeeded(node)
	}
	if _, ok := node.Value(); ok && node.Live() != a11y.LiveOff {
		g.events = append(g.events, liveRegionAnnouncement(node))
	}
}

func selectedOpt(node *consumer.Node) (bool, bool) {
	return node.IsSelected()
}

func (g *eventGenerator) NodeUpdated(oldNode, newNode *consumer.Node) {
	oldRaw, oldRawOK := oldNode.RawValue()
	newRaw, newRawOK := newNode.RawValue()
	if oldRaw != newRaw || oldRawOK != newRawOK {
		g.insertTextChangeIfNeeded(newNode)
	}
	oldFilterResult := filter(oldNode)
	newFilterResult := filter(newNode)
	if newFilterResult != consumer.FilterResultInclude {
		if oldSelected, ok := oldNode.IsSelected(); oldFilterResult == consumer.FilterResultInclude && ok && oldSelected {
			g.enqueueSelectedRowsChangeIfNeeded(oldNode)
		}
		if newFilterResult == consumer.FilterResultExcludeSubtree {
			g.removeSubtree(oldNode)
		} else {
			g.events = append(g.events, queuedEventNodeDestroyed{nodeID: newNode.ID()})
		}
		return
	}
	nodeID := newNode.ID()
	oldWrapper := nodeWrapper{oldNode}
	newWrapper := nodeWrapper{newNode}
	oldTitle, oldTitleOK := oldWrapper.title()
	newTitle, newTitleOK := newWrapper.title()
	if oldTitle != newTitle || oldTitleOK != newTitleOK {
		g.events = append(g.events, queuedEventGeneric{nodeID: nodeID, notification: "NSAccessibilityTitleChangedNotification"})
	}
	newValue := newWrapper.value()
	if oldWrapper.value() != newValue {
		event := queuedEventGeneric{nodeID: nodeID, notification: "NSAccessibilityValueChangedNotification"}
		if !newNode.IsFocused() && newValue.kind == valueBool {
			g.events = append([]queuedEvent{event}, g.events...)
		} else {
			g.events = append(g.events, event)
		}
	}
	if oldWrapper.supportsTextRanges() && newWrapper.supportsTextRanges() {
		oldSel, oldSelOK := oldWrapper.rawTextSelection()
		newSel, newSelOK := newWrapper.rawTextSelection()
		if oldSel != newSel || oldSelOK != newSelOK {
			g.events = append(g.events, queuedEventGeneric{nodeID: nodeID, notification: "NSAccessibilitySelectedTextChangedNotification"})
		}
	}
	newNodeValue, newNodeValueOK := newNode.Value()
	oldNodeValue, oldNodeValueOK := oldNode.Value()
	if newNodeValueOK && newNode.Live() != a11y.LiveOff &&
		(newNodeValue != oldNodeValue || newNodeValueOK != oldNodeValueOK ||
			newNode.Live() != oldNode.Live() ||
			oldFilterResult != consumer.FilterResultInclude) {
		g.events = append(g.events, liveRegionAnnouncement(newNode))
	}
	newSelected, newSelectedOK := selectedOpt(newNode)
	oldSelected, oldSelectedOK := selectedOpt(oldNode)
	if newSelected != oldSelected || newSelectedOK != oldSelectedOK ||
		(oldFilterResult != consumer.FilterResultInclude && newSelectedOK && newSelected) {
		g.enqueueSelectedRowsChangeIfNeeded(newNode)
	}
}

func (g *eventGenerator) FocusMoved(_, newNode *consumer.Node) {
	if newNode != nil {
		if filter(newNode) != consumer.FilterResultInclude {
			return
		}
		g.events = append(g.events, focusEvent(newNode.ID()))
	}
}

func (g *eventGenerator) NodeRemoved(node *consumer.Node) {
	g.insertTextChangeIfNeeded(node)
	if selected, ok := node.IsSelected(); ok && selected {
		g.enqueueSelectedRowsChangeIfNeeded(node)
	}
	g.events = append(g.events, queuedEventNodeDestroyed{nodeID: node.ID()})
}
