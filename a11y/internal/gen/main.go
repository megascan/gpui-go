func (s propSpec) spec() kindSpec {
	if s.kind == "enum" {
		return kindSpec{name: "enum", pv: "pv" + s.id, goType: s.id, debug: "v.String()"}
	}
	return kinds[s.kind]
}

func camel(s string) string {
	return strings.ToLower(s[:1]) + s[1:]
}

