package xkb

// Keysym is an xkb_keysym_t.
type Keysym uint32

// Raw returns the keysym value.
func (k Keysym) Raw() uint32 { return uint32(k) }

// IsKeypadKey reports whether k is a keypad key, as xkeysym does.
func (k Keysym) IsKeypadKey() bool { return k >= KEY_KP_Space && k <= KEY_KP_Equal }

// IsModifierKey reports whether k is a modifier key, as xkeysym does.
func (k Keysym) IsModifierKey() bool {
	return (k >= KEY_Shift_L && k <= KEY_Hyper_R) || (k >= KEY_ISO_Lock && k <= KEY_ISO_Level5_Lock) || k == KEY_Mode_switch || k == KEY_Num_Lock
}

