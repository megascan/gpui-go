package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

const wlImport = "github.com/megascan/gpui-go/internal/linux/wl"
const optionImport = "github.com/megascan/gpui-go/gpuiutil"

var proxyMethods = map[string]bool{
	"Ptr": true, "Interface": true, "Version": true, "ID": true, "IsAlive": true,
	"Display": true, "UserData": true, "SetUserData": true, "String": true,
	"SetQueue": true, "Marshal": true, "MarshalConstructor": true, "Dispatch": true,
	"SetListener": true, "Listener": true,
}

var reserved = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true,
	"default": true, "defer": true, "else": true, "fallthrough": true, "for": true,
	"func": true, "go": true, "goto": true, "if": true, "import": true,
	"interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
	"p": true, "a": true, "f": true, "obj": true, "wl": true, "gpuiutil": true,
	"opcode": true, "string": true, "int": true, "len": true, "new": true,
}

type universe struct {
	interfaces map[string]*iface
	enums      map[string]*enum
}

func newUniverse(ps []*protocol) (*universe, error) {
	u := &universe{interfaces: map[string]*iface{}, enums: map[string]*enum{}}
	for _, p := range ps {
		for k := range p.Interfaces {
			in := &p.Interfaces[k]
			if _, dup := u.interfaces[in.Name]; dup {
				return nil, fmt.Errorf("wlgen: interface %s declared twice", in.Name)
			}
			u.interfaces[in.Name] = in
			for j := range in.Enums {
				u.enums[in.Name+"."+in.Enums[j].Name] = &in.Enums[j]
			}
		}
	}
	return u, nil
}

func camel(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func lowerCamel(s string) string {
	c := camel(s)
	if c == "" {
		return "arg"
	}
	out := strings.ToLower(c[:1]) + c[1:]
	if reserved[out] {
		out += "_"
	}
	return out
}

func ifaceType(name string) string { return camel(name) }

func ifaceVar(name string) string { return camel(name) + "Interface" }

type generator struct {
	u         *universe
	buf       bytes.Buffer
	idents    map[string]string
	useOption bool
}

func (g *generator) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *generator) declare(ident, what string) error {
	if prev, dup := g.idents[ident]; dup {
		return fmt.Errorf("wlgen: identifier %s from %s collides with %s", ident, what, prev)
	}
	g.idents[ident] = what
	return nil
}

func (g *generator) enumType(owner *iface, ref string) (string, error) {
	full := ref
	if !strings.Contains(ref, ".") {
		full = owner.Name + "." + ref
	}
	if _, ok := g.u.enums[full]; !ok {
		return "", fmt.Errorf("wlgen: %s: unknown enum %s", owner.Name, full)
	}
	dot := strings.IndexByte(full, '.')
	return camel(full[:dot]) + camel(full[dot+1:]), nil
}

func (g *generator) checkInterface(owner *iface, name string) error {
	if name == "" {
		return nil
	}
	if _, ok := g.u.interfaces[name]; !ok {
		return fmt.Errorf("wlgen: %s: unknown interface %s", owner.Name, name)
	}
	return nil
}

func signature(m *message) string {
	var b strings.Builder
	for _, a := range m.Args {
		if a.nullable() {
			b.WriteByte('?')
		}
		switch a.Type {
		case "int":
			b.WriteByte('i')
		case "uint":
			b.WriteByte('u')
		case "fixed":
			b.WriteByte('f')
		case "string":
			b.WriteByte('s')
		case "object":
			b.WriteByte('o')
		case "new_id":
			if a.Interface == "" {
				b.WriteString("sun")
			} else {
				b.WriteByte('n')
			}
		case "array":
			b.WriteByte('a')
		case "fd":
			b.WriteByte('h')
		}
	}
	return b.String()
}

func typesList(m *message) []string {
	var out []string
	for _, a := range m.Args {
		switch {
		case a.Type == "new_id" && a.Interface == "":
			out = append(out, "nil", "nil", "nil")
		case (a.Type == "object" || a.Type == "new_id") && a.Interface != "":
			out = append(out, ifaceVar(a.Interface))
		default:
			out = append(out, "nil")
		}
	}
	return out
}

func validTypes(m *message) error {
	for _, a := range m.Args {
		switch a.Type {
		case "int", "uint", "fixed", "string", "object", "new_id", "array", "fd":
		default:
			return fmt.Errorf("wlgen: %s: argument %s has unknown type %q", m.Name, a.Name, a.Type)
		}
	}
	return nil
}

func generate(p *protocol, u *universe, pkg string, idents map[string]string) ([]byte, error) {
	g := &generator{u: u, idents: idents}
	var body generator
	body.u = u
	body.idents = idents
	for k := range p.Interfaces {
		if err := body.genInterface(&p.Interfaces[k]); err != nil {
			return nil, err
		}
	}
	g.p("// Code generated by wlgen; DO NOT EDIT.")
	g.p("")
	g.p("//go:build linux")
	g.p("")
	g.p("package %s", pkg)
	g.p("")
	if body.useOption {
		g.p("import (")
		g.p("\t%q", optionImport)
		g.p("\t%q", wlImport)
		g.p(")")
	} else {
		g.p("import %q", wlImport)
	}
	g.buf.Write(body.buf.Bytes())
	out, err := format.Source(g.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("wlgen: format %s: %w\n%s", p.file, err, g.buf.Bytes())
	}
	return out, nil
}

func (g *generator) genInterface(in *iface) error {
	version, err := in.version()
	if err != nil {
		return err
	}
	typ := ifaceType(in.Name)
	for _, id := range []string{typ, ifaceVar(in.Name)} {
		if err := g.declare(id, in.Name); err != nil {
			return err
		}
	}
	hasEvents := len(in.Events) > 0
	listener := typ + "Listener"
	if hasEvents {
		if err := g.declare(listener, in.Name+" listener"); err != nil {
			return err
		}
	}

	g.p("")
	g.p("var %s = &wl.Interface{Name: %q, Version: %d}", ifaceVar(in.Name), in.Name, version)

	g.p("")
	g.p("type %s struct {", typ)
	g.p("\twl.Proxy")
	if hasEvents {
		g.p("\tlistener %s", listener)
	}
	g.p("}")

	if err := g.genConstants(in); err != nil {
		return err
	}
	for k := range in.Enums {
		if err := g.genEnum(in, &in.Enums[k]); err != nil {
			return err
		}
	}

	g.p("")
	g.p("func init() {")
	g.p("\t%s.New = func() wl.Object { return &%s{} }", ifaceVar(in.Name), typ)
	for _, part := range []struct {
		field string
		ms    []message
	}{{"Methods", in.Requests}, {"Events", in.Events}} {
		if len(part.ms) == 0 {
			continue
		}
		g.p("\t%s.%s = []wl.Message{", ifaceVar(in.Name), part.field)
		for k := range part.ms {
			m := &part.ms[k]
			if err := validTypes(m); err != nil {
				return fmt.Errorf("%s.%w", in.Name, err)
			}
			since, err := m.since()
			if err != nil {
				return err
			}
			for _, a := range m.Args {
				if err := g.checkInterface(in, a.Interface); err != nil {
					return err
				}
			}
			line := fmt.Sprintf("{Name: %q, Signature: %q, Since: %d", m.Name, signature(m), since)
			types := typesList(m)
			allNil := true
			for _, t := range types {
				if t != "nil" {
					allNil = false
				}
			}
			if !allNil {
				line += ", Types: []*wl.Interface{" + strings.Join(types, ", ") + "}"
			}
			if m.destructor() {
				line += ", Destructor: true"
			}
			g.p("\t\t%s},", line)
		}
		g.p("\t}")
	}
	g.p("}")

	for k := range in.Requests {
		if err := g.genRequest(in, k); err != nil {
			return err
		}
	}

	if hasEvents {
		if err := g.genListener(in); err != nil {
			return err
		}
	} else {
		g.p("")
		g.p("func (p *%s) Dispatch(opcode uint32, a wl.Args) {}", typ)
	}
	return nil
}

func (g *generator) genConstants(in *iface) error {
	type sinceConst struct {
		name  string
		value uint32
	}
	var consts []sinceConst
	for _, group := range [][]message{in.Requests, in.Events} {
		for k := range group {
			m := &group[k]
			since, err := m.since()
			if err != nil {
				return err
			}
			name := ifaceType(in.Name) + camel(m.Name) + "SinceVersion"
			if err := g.declare(name, in.Name+"."+m.Name); err != nil {
				return err
			}
			consts = append(consts, sinceConst{name, since})
		}
	}
	if len(consts) == 0 {
		return nil
	}
	g.p("")
	g.p("const (")
	for _, c := range consts {
		g.p("\t%s = %d", c.name, c.value)
	}
	g.p(")")
	return nil
}

func (g *generator) genEnum(in *iface, e *enum) error {
	typ := ifaceType(in.Name) + camel(e.Name)
	if err := g.declare(typ, in.Name+"."+e.Name); err != nil {
		return err
	}
	g.p("")
	g.p("type %s uint32", typ)
	if len(e.Entries) > 0 {
		g.p("")
		g.p("const (")
		for _, en := range e.Entries {
			name := typ + camel(en.Name)
			if err := g.declare(name, in.Name+"."+e.Name+"."+en.Name); err != nil {
				return err
			}
			g.p("\t%s %s = %s", name, typ, en.Value)
		}
		g.p(")")
	}
	if e.Bitfield == "true" {
		g.p("")
		g.p("func (v %s) Contains(flags %s) bool { return v&flags == flags }", typ, typ)
	}
	return nil
}

func (g *generator) paramType(in *iface, a *arg) (string, error) {
	if a.Enum != "" && (a.Type == "int" || a.Type == "uint") {
		return g.enumType(in, a.Enum)
	}
	switch a.Type {
	case "int":
		return "int32", nil
	case "uint":
		return "uint32", nil
	case "fixed":
		return "float64", nil
	case "string":
		if a.nullable() {
			g.useOption = true
			return "gpuiutil.Option[string]", nil
		}
		return "string", nil
	case "object", "new_id":
		if a.Interface == "" {
			return "wl.Object", nil
		}
		return "*" + ifaceType(a.Interface), nil
	case "array":
		return "[]byte", nil
	case "fd":
		return "int", nil
	}
	return "", fmt.Errorf("wlgen: %s: unsupported type %s", a.Name, a.Type)
}

func argNames(m *message) []string {
	seen := map[string]int{}
	out := make([]string, len(m.Args))
	for k, a := range m.Args {
		n := lowerCamel(a.Name)
		if c := seen[n]; c > 0 {
			n = fmt.Sprintf("%s%d", n, c+1)
		}
		seen[n]++
		out[k] = n
	}
	return out
}

func (g *generator) genRequest(in *iface, opcode int) error {
	m := &in.Requests[opcode]
	typ := ifaceType(in.Name)
	method := camel(m.Name)
	if proxyMethods[method] && method != "Destroy" {
		return fmt.Errorf("wlgen: %s.%s collides with a wl.Proxy method", in.Name, m.Name)
	}
	names := argNames(m)
	var params, args []string
	var newID *arg
	for k := range m.Args {
		a := &m.Args[k]
		if a.Type == "new_id" {
			if newID != nil {
				return fmt.Errorf("wlgen: %s.%s has two new_id arguments", in.Name, m.Name)
			}
			newID = a
			if a.Interface == "" {
				params = append(params, "iface *wl.Interface", "version uint32")
				args = append(args, "wl.String(iface.Name)", "wl.Uint(version)", "wl.NewID()")
			} else {
				args = append(args, "wl.NewID()")
			}
			continue
		}
		pt, err := g.paramType(in, a)
		if err != nil {
			return err
		}
		params = append(params, names[k]+" "+pt)
		args = append(args, g.marshalArg(a, names[k]))
	}
	argList := ""
	if len(args) > 0 {
		argList = ", " + strings.Join(args, ", ")
	}
	g.p("")
	switch {
	case newID == nil:
		g.p("func (p *%s) %s(%s) {", typ, method, strings.Join(params, ", "))
		g.p("\tp.Marshal(%d%s)", opcode, argList)
	case newID.Interface == "":
		g.p("func (p *%s) %s(%s) wl.Object {", typ, method, strings.Join(params, ", "))
		g.p("\treturn p.MarshalConstructor(%d, iface, version%s)", opcode, argList)
	default:
		child := ifaceType(newID.Interface)
		g.p("func (p *%s) %s(%s) *%s {", typ, method, strings.Join(params, ", "), child)
		g.p("\tobj, _ := p.MarshalConstructor(%d, %s, 0%s).(*%s)", opcode, ifaceVar(newID.Interface), argList, child)
		g.p("\treturn obj")
	}
	g.p("}")
	return nil
}

func (g *generator) marshalArg(a *arg, name string) string {
	switch a.Type {
	case "int":
		if a.Enum != "" {
			return "wl.Int(int32(" + name + "))"
		}
		return "wl.Int(" + name + ")"
	case "uint":
		if a.Enum != "" {
			return "wl.Uint(uint32(" + name + "))"
		}
		return "wl.Uint(" + name + ")"
	case "fixed":
		return "wl.FixedArg(" + name + ")"
	case "string":
		if a.nullable() {
			return "wl.NullableString(" + name + ")"
		}
		return "wl.String(" + name + ")"
	case "object":
		if a.Interface == "" {
			return "wl.AnyObjectArg(" + name + ")"
		}
		return "wl.ObjectArg(" + name + ")"
	case "array":
		return "wl.Array(" + name + ")"
	case "fd":
		return "wl.FD(" + name + ")"
	}
	return ""
}

func (g *generator) genListener(in *iface) error {
	typ := ifaceType(in.Name)
	listener := typ + "Listener"
	g.p("")
	g.p("type %s struct {", listener)
	for k := range in.Events {
		m := &in.Events[k]
		names := argNames(m)
		var params []string
		for j := range m.Args {
			pt, err := g.paramType(in, &m.Args[j])
			if err != nil {
				return err
			}
			params = append(params, names[j]+" "+pt)
		}
		g.p("\t%s func(%s)", camel(m.Name), strings.Join(params, ", "))
	}
	g.p("}")
	g.p("")
	g.p("func (p *%s) SetListener(l %s) { p.listener = l }", typ, listener)
	g.p("")
	g.p("func (p *%s) Listener() %s { return p.listener }", typ, listener)
	g.p("")
	g.p("func (p *%s) Dispatch(opcode uint32, a wl.Args) {", typ)
	g.p("\tswitch opcode {")
	for k := range in.Events {
		m := &in.Events[k]
		names := argNames(m)
		g.p("\tcase %d:", k)
		var fds, created []string
		for j := range m.Args {
			a := &m.Args[j]
			expr, err := g.decodeArg(in, a, j)
			if err != nil {
				return err
			}
			if strings.HasSuffix(expr, ")") && (a.Type == "object" || a.Type == "new_id") && a.Interface != "" {
				g.p("\t\t%s, _ := %s", names[j], expr)
			} else {
				g.p("\t\t%s := %s", names[j], expr)
			}
			if a.Type == "fd" {
				fds = append(fds, names[j])
			}
			if a.Type == "new_id" {
				created = append(created, fmt.Sprintf("a.NewID(%d)", j))
			}
		}
		g.p("\t\tif f := p.listener.%s; f != nil {", camel(m.Name))
		g.p("\t\t\tf(%s)", strings.Join(names, ", "))
		if len(fds) > 0 || len(created) > 0 {
			g.p("\t\t} else {")
			for _, fd := range fds {
				g.p("\t\t\twl.CloseFD(%s)", fd)
			}
			for _, c := range created {
				g.p("\t\t\twl.DiscardNewID(%s)", c)
			}
		}
		g.p("\t\t}")
	}
	g.p("\t}")
	g.p("}")
	return nil
}

func (g *generator) decodeArg(in *iface, a *arg, index int) (string, error) {
	switch a.Type {
	case "int":
		if a.Enum != "" {
			t, err := g.enumType(in, a.Enum)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("%s(a.Int(%d))", t, index), nil
		}
		return fmt.Sprintf("a.Int(%d)", index), nil
	case "uint":
		if a.Enum != "" {
			t, err := g.enumType(in, a.Enum)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("%s(a.Uint(%d))", t, index), nil
		}
		return fmt.Sprintf("a.Uint(%d)", index), nil
	case "fixed":
		return fmt.Sprintf("a.Fixed(%d)", index), nil
	case "string":
		if a.nullable() {
			g.useOption = true
			return fmt.Sprintf("a.NullableString(%d)", index), nil
		}
		return fmt.Sprintf("a.String(%d)", index), nil
	case "object":
		if a.Interface == "" {
			return fmt.Sprintf("a.Object(%d)", index), nil
		}
		return fmt.Sprintf("a.Object(%d).(*%s)", index, ifaceType(a.Interface)), nil
	case "new_id":
		if a.Interface == "" {
			return "", fmt.Errorf("wlgen: %s: event with an untyped new_id", in.Name)
		}
		return fmt.Sprintf("a.NewID(%d).(*%s)", index, ifaceType(a.Interface)), nil
	case "array":
		return fmt.Sprintf("a.Array(%d)", index), nil
	case "fd":
		return fmt.Sprintf("a.FD(%d)", index), nil
	}
	return "", fmt.Errorf("wlgen: %s: unsupported type %s", a.Name, a.Type)
}
