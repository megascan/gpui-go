// Command actiongen expands //gpui:action struct directives (upstream #[derive(Action)] and actions!) into <file>_gen.go.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strconv"
	"strings"
)

const (
	directive     = "//gpui:action"
	header        = "// Code generated by actiongen; DO NOT EDIT."
	gpuiPkg       = "github.com/megascan/gpui-go"
	jsonschemaPkg = "github.com/megascan/gpui-go/internal/jsonschema"
)

var reservedImports = []string{"gpui", "json", "jsontext", "reflect", "errors", "jsonschema"}

func main() {
	self := flag.Bool("self", false, "generate for the root gpui package, which refers to its own identifiers without a qualifier")
	flag.Parse()
	if err := run(flag.Args(), *self); err != nil {
		fmt.Fprintln(os.Stderr, "actiongen:", err)
		os.Exit(1)
	}
}

func run(args []string, self bool) error {
	files := args
	if len(files) == 0 {
		entries, err := os.ReadDir(".")
		if err != nil {
			return err
		}
		for _, e := range entries {
			n := e.Name()
			if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || strings.HasSuffix(n, "_gen.go") {
				continue
			}
			files = append(files, n)
		}
	}
	for _, name := range files {
		src, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		out, err := Generate(name, src, self)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if out == nil {
			continue
		}
		target := strings.TrimSuffix(name, ".go") + "_gen.go"
		if err := os.WriteFile(target, out, 0o644); err != nil {
			return err
		}
	}
	return nil
}

type action struct {
	typeName      string
	name          string
	noJSON        bool
	noRegister    bool
	unit          bool
	aliases       []string
	deprecated    string
	documentation string
}

type argument struct {
	key      string
	value    string
	hasValue bool
}

// Generate returns the formatted <file>_gen.go source for the //gpui:action directives in src, or nil when the file has none.
func Generate(name string, src []byte, self bool) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, name, src, parser.ParseComments)
	if err != nil {
		return nil, err
	}

	var actions []action
	claimed := map[token.Pos]bool{}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			group := ts.Doc
			if group == nil && len(gd.Specs) == 1 {
				group = gd.Doc
			}
			if group == nil {
				continue
			}
			var dir *ast.Comment
			for _, c := range group.List {
				if !isDirective(c.Text) {
					continue
				}
				if dir != nil {
					return nil, fmt.Errorf("%s: multiple %s directives on one type", ts.Name.Name, directive)
				}
				dir = c
			}
			if dir == nil {
				continue
			}
			claimed[dir.Pos()] = true
			a, err := buildAction(ts, group, dir)
			if err != nil {
				return nil, err
			}
			actions = append(actions, a)
		}
	}

	for _, group := range f.Comments {
		for _, c := range group.List {
			if isDirective(c.Text) && !claimed[c.Pos()] {
				return nil, fmt.Errorf("line %d: misplaced %s directive: attach it to a struct type declaration", fset.Position(c.Pos()).Line, directive)
			}
		}
	}

	if len(actions) == 0 {
		return nil, nil
	}
	return render(f.Name.Name, actions, self)
}

func isDirective(text string) bool {
	return text == directive || strings.HasPrefix(text, directive+" ") || strings.HasPrefix(text, directive+"\t")
}

func buildAction(ts *ast.TypeSpec, group *ast.CommentGroup, dir *ast.Comment) (action, error) {
	typeName := ts.Name.Name
	if ts.TypeParams != nil && len(ts.TypeParams.List) > 0 {
		return action{}, fmt.Errorf("%s: %s: generic types cannot be actions", typeName, directive)
	}
	st, ok := ts.Type.(*ast.StructType)
	if !ok {
		return action{}, fmt.Errorf("%s: %s: only struct types can be actions", typeName, directive)
	}
	args, err := parseArguments(strings.TrimPrefix(dir.Text, directive))
	if err != nil {
		return action{}, fmt.Errorf("%s: %s: %w", typeName, directive, err)
	}

	a := action{typeName: typeName, unit: len(st.Fields.List) == 0}
	var namespace string
	var name string
	seen := map[string]bool{}
	for _, arg := range args {
		if seen[arg.key] {
			return action{}, fmt.Errorf("%s: %s: '%s' argument specified multiple times", typeName, directive, arg.key)
		}
		seen[arg.key] = true
		switch arg.key {
		case "namespace":
			if !arg.hasValue || !token.IsIdentifier(arg.value) {
				return action{}, fmt.Errorf("%s: %s: namespace must be an identifier", typeName, directive)
			}
			namespace = arg.value
		case "name":
			if !arg.hasValue || arg.value == "" {
				return action{}, fmt.Errorf("%s: %s: name must not be empty", typeName, directive)
			}
			name = arg.value
		case "no_json":
			if arg.hasValue {
				return action{}, fmt.Errorf("%s: %s: 'no_json' takes no value", typeName, directive)
			}
			a.noJSON = true
		case "no_register":
			if arg.hasValue {
				return action{}, fmt.Errorf("%s: %s: 'no_register' takes no value", typeName, directive)
			}
			a.noRegister = true
		case "deprecated_aliases":
			if !arg.hasValue {
				return action{}, fmt.Errorf("%s: %s: 'deprecated_aliases' needs a comma-separated value", typeName, directive)
			}
			for _, alias := range strings.Split(arg.value, ",") {
				if alias == "" {
					return action{}, fmt.Errorf("%s: %s: empty deprecated alias", typeName, directive)
				}
				a.aliases = append(a.aliases, alias)
			}
		case "deprecated":
			if !arg.hasValue {
				return action{}, fmt.Errorf("%s: %s: 'deprecated' needs a message", typeName, directive)
			}
			a.deprecated = arg.value
		default:
			return action{}, fmt.Errorf("%s: %s: '%s' argument not recognized, expected 'namespace', 'name', 'no_json', 'no_register', 'deprecated_aliases', or 'deprecated'", typeName, directive, arg.key)
		}
	}

	if strings.Contains(name, "::") {
		return action{}, fmt.Errorf("%s: %s: name %q must not contain '::', also specify namespace instead", typeName, directive, name)
	}
	if name == "" {
		name = typeName
	}
	a.name = name
	if namespace != "" {
		a.name = namespace + "::" + name
	}
	for _, reserved := range reservedImports {
		if typeName == reserved {
			return action{}, fmt.Errorf("%s: %s: type name collides with a generated import", typeName, directive)
		}
	}
	a.documentation = documentation(group)
	return a, nil
}

func parseArguments(s string) ([]argument, error) {
	var args []argument
	rest := s
	for {
		rest = strings.TrimLeft(rest, " \t")
		if rest == "" {
			return args, nil
		}
		i := strings.IndexAny(rest, "= \t")
		if i < 0 {
			args = append(args, argument{key: rest})
			return args, nil
		}
		key := rest[:i]
		if rest[i] != '=' {
			args = append(args, argument{key: key})
			rest = rest[i:]
			continue
		}
		rest = rest[i+1:]
		if strings.HasPrefix(rest, `"`) {
			quoted, err := strconv.QuotedPrefix(rest)
			if err != nil {
				return nil, fmt.Errorf("'%s' has an unterminated quoted value", key)
			}
			value, err := strconv.Unquote(quoted)
			if err != nil {
				return nil, fmt.Errorf("'%s' has an invalid quoted value", key)
			}
			args = append(args, argument{key: key, value: value, hasValue: true})
			rest = rest[len(quoted):]
			if rest != "" && rest[0] != ' ' && rest[0] != '\t' {
				return nil, fmt.Errorf("'%s' value must be followed by a space", key)
			}
			continue
		}
		j := strings.IndexAny(rest, " \t")
		if j < 0 {
			j = len(rest)
		}
		args = append(args, argument{key: key, value: rest[:j], hasValue: true})
		rest = rest[j:]
	}
}

func documentation(group *ast.CommentGroup) string {
	var lines []string
	for _, c := range group.List {
		if strings.HasPrefix(c.Text, "//gpui:") || strings.HasPrefix(c.Text, "//go:") {
			continue
		}
		if body, ok := strings.CutPrefix(c.Text, "//"); ok {
			lines = append(lines, strings.TrimSpace(body))
			continue
		}
		body := strings.TrimSuffix(strings.TrimPrefix(c.Text, "/*"), "*/")
		for _, line := range strings.Split(body, "\n") {
			lines = append(lines, strings.TrimSpace(line))
		}
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

func render(pkg string, actions []action, self bool) ([]byte, error) {
	var needJSON, needJSONText, needErrors, needReflect, needSchema bool
	for _, a := range actions {
		if a.noRegister {
			continue
		}
		needReflect = true
		needJSONText = true
		if a.noJSON {
			needErrors = true
		} else if !a.unit {
			needJSON = true
			needSchema = true
		}
	}

	q := "gpui."
	if self {
		q = ""
	}

	var std, third []string
	if needErrors {
		std = append(std, `"errors"`)
	}
	if needJSON {
		std = append(std, `"encoding/json/v2"`)
	}
	if needJSONText {
		std = append(std, `"encoding/json/jsontext"`)
	}
	if needReflect {
		std = append(std, `"reflect"`)
	}
	if needSchema {
		third = append(third, strconv.Quote(jsonschemaPkg))
	}
	if !self {
		third = append(third, strconv.Quote(gpuiPkg))
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n\npackage %s\n\n", header, pkg)
	if len(std)+len(third) > 0 {
		b.WriteString("import (\n")
		for _, p := range std {
			fmt.Fprintf(&b, "\t%s\n", p)
		}
		if len(std) > 0 && len(third) > 0 {
			b.WriteString("\n")
		}
		for _, p := range third {
			fmt.Fprintf(&b, "\t%s\n", p)
		}
		b.WriteString(")\n")
	}

	for _, a := range actions {
		t := a.typeName
		fmt.Fprintf(&b, "\nfunc (%s) Name() string {\n\treturn %s\n}\n", t, strconv.Quote(a.name))
		fmt.Fprintf(&b, "\nfunc (a %s) BoxedClone() %sAction {\n\treturn a\n}\n", t, q)
		fmt.Fprintf(&b, "\nfunc (a %s) PartialEq(other %sAction) bool {\n\to, ok := other.(%s)\n\treturn ok && a == o\n}\n", t, q, t)
		if a.noRegister {
			continue
		}
		fmt.Fprintf(&b, "\nfunc init() {\n\t%sRegisterAction(%sActionData{\n", q, q)
		fmt.Fprintf(&b, "\t\tName: %s,\n", strconv.Quote(a.name))
		fmt.Fprintf(&b, "\t\tType: reflect.TypeFor[%s](),\n", t)
		switch {
		case a.unit:
			fmt.Fprintf(&b, "\t\tBuild: func(jsontext.Value) (%sAction, error) {\n\t\t\treturn %s{}, nil\n\t\t},\n", q, t)
		case a.noJSON:
			fmt.Fprintf(&b, "\t\tBuild: func(jsontext.Value) (%sAction, error) {\n\t\t\treturn nil, errors.New(%s)\n\t\t},\n", q, strconv.Quote(a.name+" cannot be built from JSON"))
		default:
			fmt.Fprintf(&b, "\t\tBuild: func(value jsontext.Value) (%sAction, error) {\n\t\t\tvar a %s\n\t\t\tif err := json.Unmarshal(value, &a); err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n\t\t\treturn a, nil\n\t\t},\n", q, t)
			fmt.Fprintf(&b, "\t\tJSONSchema: func() *jsonschema.Schema {\n\t\t\treturn jsonschema.NewGenerator().Reflect(reflect.TypeFor[%s]())\n\t\t},\n", t)
		}
		if len(a.aliases) > 0 {
			quoted := make([]string, len(a.aliases))
			for i, alias := range a.aliases {
				quoted[i] = strconv.Quote(alias)
			}
			fmt.Fprintf(&b, "\t\tDeprecatedAliases: []string{%s},\n", strings.Join(quoted, ", "))
		}
		if a.deprecated != "" {
			fmt.Fprintf(&b, "\t\tDeprecationMessage: %s,\n", strconv.Quote(a.deprecated))
		}
		if a.documentation != "" {
			fmt.Fprintf(&b, "\t\tDocumentation: %s,\n", strconv.Quote(a.documentation))
		}
		b.WriteString("\t})\n}\n")
	}

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return out, nil
}
