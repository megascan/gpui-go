package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

type program struct {
	Name     string
	Vertex   string
	Fragment string
}

type variant struct {
	Name    string
	Sources []string
}

var programs = []program{
	{"quads", "vs_quad", "fs_quad"},
	{"opaque_quads", "vs_opaque_quad", "fs_opaque_quad"},
	{"shadows", "vs_shadow", "fs_shadow"},
	{"path_tiles", "vs_path_tile", "fs_path_tile"},
	{"underlines", "vs_underline", "fs_underline"},
	{"mono_sprites", "vs_mono_sprite", "fs_mono_sprite"},
	{"poly_sprites", "vs_poly_sprite", "fs_poly_sprite"},
	{"surfaces", "vs_surface", "fs_surface"},
}

var webVariants = []variant{
	{"webgl", []string{"shaders.wgsl", "shaders_webgl.wgsl"}},
}

type uniformBlock struct {
	Name     string
	Instance string
	Group    int
	Binding  int
}

type texture struct {
	Name           string
	Group          int
	Binding        int
	SamplerGroup   int
	SamplerBinding int
}

type stage struct {
	File          string
	UniformBlocks []uniformBlock
	Textures      []texture
	Uniforms      []string
	Attributes    []string
}

type binding struct {
	Group   int
	Binding int
}

var (
	blockRe     = regexp.MustCompile(`(?m)^layout\(std140\) uniform (\w+) \{ \w+ (_group_(\d+)_binding_(\d+)_\w+); \};`)
	samplerRe   = regexp.MustCompile(`(?m)^uniform highp [iu]?sampler\w* (_group_(\d+)_binding_(\d+)_\w+);`)
	uniformRe   = regexp.MustCompile(`(?m)^uniform (?:\w+ )?\w+ (\w+);`)
	attributeRe = regexp.MustCompile(`(?m)^(?:layout\(location = \d+\) )?(?:smooth |flat )?in \w+ (\w+);`)
	globalRe    = regexp.MustCompile(`@group\((\d+)\)\s*@binding\((\d+)\)\s*var(?:<[^>]*>)?\s+(\w+)\s*:`)
	sampleRe    = regexp.MustCompile(`textureSample\w*\(\s*(\w+)\s*,\s*(\w+)`)
)

func main() {
	shaders := flag.String("shaders", "../../render/wgpu/shaders", "directory holding the WGSL sources")
	out := flag.String("out", ".", "output directory")
	flag.Parse()
	naga, err := findNaga()
	if err != nil {
		fmt.Println("glslgen: naga not found, keeping the committed GLSL")
		return
	}
	if err := run(naga, *shaders, *out); err != nil {
		fmt.Fprintln(os.Stderr, "glslgen:", err)
		os.Exit(1)
	}
}

func findNaga() (string, error) {
	var candidates []string
	if p := os.Getenv("NAGA"); p != "" {
		candidates = append(candidates, p)
	}
	if home, err := os.UserHomeDir(); err == nil {
		candidates = append(candidates, filepath.Join(home, ".cargo", "bin", "naga"))
	}
	if p, err := exec.LookPath("naga"); err == nil {
		candidates = append(candidates, p)
	}
	for _, c := range candidates {
		if exec.Command(c, "--version").Run() == nil {
			return c, nil
		}
	}
	return "", errors.New("naga not found")
}

func run(naga, shaders, out string) error {
	var gen bytes.Buffer
	gen.WriteString("// Code generated by glslgen; DO NOT EDIT.\n\npackage webglsl\n\nimport _ \"embed\"\n\n")
	var table bytes.Buffer
	for _, v := range webVariants {
		var src []byte
		for _, f := range v.Sources {
			b, err := os.ReadFile(filepath.Join(shaders, f))
			if err != nil {
				return fmt.Errorf("read %s: %w", f, err)
			}
			src = append(src, b...)
		}
		sum := sha256.Sum256(src)
		fmt.Fprintf(&gen, "const %sWGSLSHA256 = %q\n\n", exportName(v.Name), hex.EncodeToString(sum[:]))
		samplers := samplerPairs(string(src))
		fmt.Fprintf(&table, "var %sPrograms = []Program{\n", lowerName(v.Name))
		for _, p := range programs {
			vs, err := translate(naga, src, v.Name, p.Vertex, "vert", out, samplers)
			if err != nil {
				return err
			}
			fs, err := translate(naga, src, v.Name, p.Fragment, "frag", out, samplers)
			if err != nil {
				return err
			}
			vsVar := lowerName(v.Name) + exportName(p.Vertex) + "Source"
			fsVar := lowerName(v.Name) + exportName(p.Fragment) + "Source"
			fmt.Fprintf(&gen, "//go:embed %s\nvar %s string\n\n//go:embed %s\nvar %s string\n\n", vs.File, vsVar, fs.File, fsVar)
			fmt.Fprintf(&table, "{Name: %q, VertexEntry: %q, FragmentEntry: %q, Vertex: %s, Fragment: %s},\n",
				p.Name, p.Vertex, p.Fragment, stageLiteral(vs, vsVar), stageLiteral(fs, fsVar))
		}
		table.WriteString("}\n\n")
	}
	gen.Write(table.Bytes())
	formatted, err := format.Source(gen.Bytes())
	if err != nil {
		return fmt.Errorf("format generated code: %w", err)
	}
	return os.WriteFile(filepath.Join(out, "webglsl_gen.go"), formatted, 0o644)
}

func translate(naga string, src []byte, variantName, entry, ext, out string, samplers map[binding]binding) (stage, error) {
	file := fmt.Sprintf("%s_%s.%s.glsl", variantName, entry, ext)
	path := filepath.Join(out, file)
	tmp := filepath.Join(out, fmt.Sprintf(".%s_%s.%s", variantName, entry, ext))
	defer os.Remove(tmp)
	cmd := exec.Command(naga, "--stdin-file-path", variantName+".wgsl", "--entry-point", entry, "--profile", "es300", tmp)
	cmd.Stdin = bytes.NewReader(src)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return stage{}, fmt.Errorf("naga %s %s: %w: %s", variantName, entry, err, stderr.String())
	}
	glsl, err := os.ReadFile(tmp)
	if err != nil {
		return stage{}, fmt.Errorf("read naga output: %w", err)
	}
	if err := os.WriteFile(path, glsl, 0o644); err != nil {
		return stage{}, fmt.Errorf("write %s: %w", file, err)
	}
	st := reflect(string(glsl), ext == "vert", samplers)
	st.File = file
	return st, nil
}

func reflect(glsl string, vertex bool, samplers map[binding]binding) stage {
	var st stage
	reserved := map[string]bool{}
	for _, m := range blockRe.FindAllStringSubmatch(glsl, -1) {
		st.UniformBlocks = append(st.UniformBlocks, uniformBlock{Name: m[1], Instance: m[2], Group: atoi(m[3]), Binding: atoi(m[4])})
	}
	for _, m := range samplerRe.FindAllStringSubmatch(glsl, -1) {
		t := texture{Name: m[1], Group: atoi(m[2]), Binding: atoi(m[3]), SamplerGroup: -1, SamplerBinding: -1}
		if s, ok := samplers[binding{t.Group, t.Binding}]; ok {
			t.SamplerGroup, t.SamplerBinding = s.Group, s.Binding
		}
		st.Textures = append(st.Textures, t)
		reserved[t.Name] = true
	}
	for _, m := range uniformRe.FindAllStringSubmatch(glsl, -1) {
		if !reserved[m[1]] {
			st.Uniforms = append(st.Uniforms, m[1])
		}
	}
	if vertex {
		for _, m := range attributeRe.FindAllStringSubmatch(glsl, -1) {
			st.Attributes = append(st.Attributes, m[1])
		}
	}
	return st
}

func samplerPairs(wgsl string) map[binding]binding {
	globals := map[string]binding{}
	for _, m := range globalRe.FindAllStringSubmatch(wgsl, -1) {
		globals[m[3]] = binding{atoi(m[1]), atoi(m[2])}
	}
	pairs := map[binding]binding{}
	for _, m := range sampleRe.FindAllStringSubmatch(wgsl, -1) {
		t, ok1 := globals[m[1]]
		s, ok2 := globals[m[2]]
		if ok1 && ok2 {
			pairs[t] = s
		}
	}
	return pairs
}

func stageLiteral(st stage, sourceVar string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Stage{File: %q, Source: %s", st.File, sourceVar)
	if len(st.UniformBlocks) > 0 {
		b.WriteString(", UniformBlocks: []UniformBlock{")
		for _, u := range st.UniformBlocks {
			fmt.Fprintf(&b, "{Name: %q, Instance: %q, Group: %d, Binding: %d},", u.Name, u.Instance, u.Group, u.Binding)
		}
		b.WriteString("}")
	}
	if len(st.Textures) > 0 {
		b.WriteString(", Textures: []Texture{")
		for _, t := range st.Textures {
			fmt.Fprintf(&b, "{Name: %q, Group: %d, Binding: %d, Unit: %d, SamplerGroup: %d, SamplerBinding: %d},",
				t.Name, t.Group, t.Binding, textureUnit(t.Group, t.Binding), t.SamplerGroup, t.SamplerBinding)
		}
		b.WriteString("}")
	}
	if len(st.Uniforms) > 0 {
		fmt.Fprintf(&b, ", Uniforms: %s", stringSlice(st.Uniforms))
	}
	if len(st.Attributes) > 0 {
		fmt.Fprintf(&b, ", Attributes: %s", stringSlice(st.Attributes))
	}
	b.WriteString("}")
	return b.String()
}

func textureUnit(group, binding int) int {
	return group*16 + binding
}

func stringSlice(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func exportName(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func lowerName(s string) string {
	e := exportName(s)
	return strings.ToLower(e[:1]) + e[1:]
}

func atoi(s string) int {
	n, _ := strconv.Atoi(s)
	return n
}
