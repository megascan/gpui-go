// Command stylegen expands the tables of upstream's gpui_macros style macros (style_helpers! and the eight *_style_methods!) into Styled[S] methods.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

const header = "// Code generated by stylegen; DO NOT EDIT."

const gpuiutilPkg = "github.com/megascan/gpui-go/gpuiutil"

type boxStylePrefix struct {
	prefix          string
	autoAllowed     bool
	fields          []string
	docStringPrefix string
}

type lengthTokens struct {
	fn  string
	arg string
}

type boxStyleSuffix struct {
	suffix          string
	tokens          lengthTokens
	docStringSuffix string
}

type cornerStylePrefix struct {
	prefix          string
	fields          []string
	docStringPrefix string
}

type cornerStyleSuffix = boxStyleSuffix

type borderStylePrefix = cornerStylePrefix

type borderStyleSuffix = boxStyleSuffix

type macro struct {
	name string
	gen  func(g *gen)
}

var macros = []macro{
	{"style_helpers", (*gen).styleHelpers},
	{"visibility_style_methods", (*gen).visibilityStyleMethods},
	{"margin_style_methods", (*gen).marginStyleMethods},
	{"padding_style_methods", (*gen).paddingStyleMethods},
	{"position_style_methods", (*gen).positionStyleMethods},
	{"overflow_style_methods", (*gen).overflowStyleMethods},
	{"cursor_style_methods", (*gen).cursorStyleMethods},
	{"border_style_methods", (*gen).borderStyleMethods},
	{"box_shadow_style_methods", (*gen).boxShadowStyleMethods},
}

func main() {
	out := flag.String("out", "styled_gen.go", "output file")
	pkg := flag.String("pkg", "gpui", "package name")
	only := flag.String("macros", "", "comma-separated macro names to expand (default all)")
	flag.Parse()
	var names []string
	if *only != "" {
		names = strings.Split(*only, ",")
	}
	src, err := Generate(*pkg, names)
	if err != nil {
		fmt.Fprintln(os.Stderr, "stylegen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "stylegen:", err)
		os.Exit(1)
	}
}

type gen struct {
	buf     bytes.Buffer
	methods []string
}

// Generate returns the formatted Go source of the Styled[S] methods of the named macros (all when names is empty), in upstream's invocation order.
func Generate(pkg string, names []string) ([]byte, error) {
	want := map[string]bool{}
	for _, n := range names {
		want[n] = true
	}
	for n := range want {
		found := false
		for _, m := range macros {
			if m.name == n {
				found = true
			}
		}
		if !found {
			return nil, fmt.Errorf("unknown macro %q", n)
		}
	}
	g := &gen{}
	fmt.Fprintf(&g.buf, "%s\n\npackage %s\n\nimport \"%s\"\n", header, pkg, gpuiutilPkg)
	for _, m := range macros {
		if len(want) == 0 || want[m.name] {
			m.gen(g)
		}
	}
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format: %w", err)
	}
	return src, nil
}

// MethodNames returns the upstream (snake_case) method names in generation order.
func MethodNames(names []string) []string {
	g := &gen{}
	want := map[string]bool{}
	for _, n := range names {
		want[n] = true
	}
	for _, m := range macros {
		if len(want) == 0 || want[m.name] {
			m.gen(g)
		}
	}
	return g.methods
}

func goName(snake string) string {
	var b strings.Builder
	parts := strings.Split(snake, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i > 0 && isDigit(parts[i-1][len(parts[i-1])-1]) && isDigit(p[0]) {
			b.WriteByte('_')
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func isDigit(c byte) bool { return c >= '0' && c <= '9' }

func fieldPath(field string) string {
	segs := strings.Split(strings.ReplaceAll(field, " ", ""), ".")
	for i, s := range segs {
		segs[i] = goName(s)
	}
	return strings.Join(segs, ".")
}

func (g *gen) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *gen) doc(method, doc string) {
	lines := strings.Split(doc, "\n")
	first := lines[0]
	switch {
	case strings.HasPrefix(first, "Set "):
		first = "sets " + first[len("Set "):]
	default:
		first = strings.ToLower(first[:1]) + first[1:]
	}
	lines[0] = goName(method) + " " + first
	g.buf.WriteByte('\n')
	for _, l := range lines {
		if l == "" {
			g.p("//")
		} else {
			g.p("// %s", l)
		}
	}
}

func (g *gen) begin(method, doc, params string) {
	g.methods = append(g.methods, method)
	g.doc(method, doc)
	g.p("func (s *Styled[S]) %s(%s) S {", goName(method), params)
}

func (g *gen) end() {
	g.p("\treturn s.self")
	g.p("}")
}

func (g *gen) simple(method, doc string, assignments ...string) {
	g.begin(method, doc, "")
	for _, a := range assignments {
		g.p("\ts.self.Style().%s", a)
	}
	g.end()
}

func lengthExpr(t lengthTokens, negate bool) string {
	var e string
	switch t.fn {
	case "px":
		e = "Px(" + t.arg + ")"
	case "rems":
		e = "Rems(" + t.arg + ")"
	case "relative":
		e = "Relative(" + t.arg + ")"
	case "auto":
		e = "Auto()"
	default:
		panic("stylegen: unknown length constructor " + t.fn)
	}
	if !negate {
		return e
	}
	if t.fn == "px" || t.fn == "rems" {
		return "(-" + e + ")"
	}
	return e + ".Neg()"
}

func (g *gen) generatePredefinedSetter(name, length string, fields []string, tokens lengthTokens, lengthType string, negate bool, doc string) {
	negationQualifier := ""
	if negate {
		negationQualifier = "_neg"
	}
	method := name + negationQualifier
	if length != "" {
		method += "_" + length
	}
	g.begin(method, doc, "")
	g.p("\tstyle := s.self.Style()")
	for _, f := range fields {
		g.p("\tstyle.%s = gpuiutil.Some(%s.To%s())", fieldPath(f), lengthExpr(tokens, negate), lengthType)
	}
	g.end()
}

func (g *gen) generateCustomValueSetter(prefix, lengthType string, fields []string, doc string) {
	g.begin(prefix, doc, "length Into"+lengthType)
	g.p("\tstyle := s.self.Style()")
	for _, f := range fields {
		g.p("\tstyle.%s = gpuiutil.Some(length.To%s())", fieldPath(f), lengthType)
	}
	g.end()
}

func (g *gen) generateBoxStyleMethods(prefixes []boxStylePrefix, suffixes []boxStyleSuffix) {
	for _, bp := range prefixes {
		lengthType := "DefiniteLength"
		if bp.autoAllowed {
			lengthType = "Length"
		}
		g.generateCustomValueSetter(bp.prefix, lengthType, bp.fields, bp.docStringPrefix)
		for _, bs := range suffixes {
			doc := bp.docStringPrefix + "\n\n" + bs.docStringSuffix
			if bs.suffix != "auto" || bp.autoAllowed {
				g.generatePredefinedSetter(bp.prefix, bs.suffix, bp.fields, bs.tokens, lengthType, false, doc)
			}
			if bs.suffix != "auto" {
				g.generatePredefinedSetter(bp.prefix, bs.suffix, bp.fields, bs.tokens, lengthType, true, doc)
			}
		}
	}
}

func (g *gen) styleHelpers() {
	g.generateBoxStyleMethods(boxPrefixes(), boxStyleSuffixes())
	for _, cp := range cornerPrefixes() {
		g.generateCustomValueSetter(cp.prefix, "AbsoluteLength", cp.fields, cp.docStringPrefix)
		for _, cs := range cornerSuffixes() {
			g.generatePredefinedSetter(cp.prefix, cs.suffix, cp.fields, cs.tokens, "AbsoluteLength", false, cp.docStringPrefix+"\n\n"+cs.docStringSuffix)
		}
	}
}

