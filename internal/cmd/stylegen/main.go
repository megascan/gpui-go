func (g *gen) boxShadowStyleMethods() {
	const docs = "\n[Docs](https://tailwindcss.com/docs/box-shadow)"
	g.begin("shadow", "Sets the box shadow of the element."+docs, "shadows []BoxShadow")
	g.p("\ts.self.Style().BoxShadow = gpuiutil.Some(shadows)")
	g.end()
	g.simple("shadow_none", "Clears the box shadow of the element."+docs, "BoxShadow = gpuiutil.Some([]BoxShadow(nil))")
	for _, bs := range boxShadows {
		g.begin(bs.method, "Sets the box shadow of the element."+docs, "")
		g.p("\ts.self.Style().BoxShadow = gpuiutil.Some([]BoxShadow{")
		for _, sh := range bs.shadows {
			e := fmt.Sprintf("NewBoxShadow(Px(0.), Px(%s), NewHsla(0., 0., 0., %s))", sh.y, sh.alpha)
			if sh.blur != "" {
				e += fmt.Sprintf(".BlurRadius(Px(%s))", sh.blur)
			}
			if sh.spread != "" {
				e += fmt.Sprintf(".SpreadRadius(Px(%s))", sh.spread)
			}
			g.p("\t\t%s,", e)
		}
		g.p("\t})")
		g.end()
	}
}
