func lintTree(t *testing.T, files map[string]string) []Problem {
	t.Helper()
	root := t.TempDir()
	tree := map[string]string{
		"go.mod":                              "module example.com/m\n\ngo 1.27\n",
		"docs/port/parity/styled-methods.tsv": "# rust_method\tgo_method\tmacro\tsource\nw_0p5\tW0p5\tstyle_helpers\tstyles.rs:1\n",
	}
	for k, v := range files {
		tree[k] = v
	}
	writeTree(t, root, tree)
	probs, err := Lint(root)
	if err != nil {
		t.Fatal(err)
	}
	return probs
}

func TestLint_Imports(t *testing.T) {
	const pkg = "package x\n\nimport _ \"example.com/m/%s\"\n"
	tests := []struct {
		name    string
		files   map[string]string
		wantMsg string
	}{
		{
			name:    "root imports platform",
			files:   map[string]string{"root.go": strings.Replace(pkg, "%s", "platform/linux", 1), "platform/linux/x_linux.go": "package linux\n"},
			wantMsg: "root package imports platform/linux",
		},
		{
			name:  "root imports allowed internal",
			files: map[string]string{"root.go": strings.Replace(pkg, "%s", "internal/taffy", 1), "internal/taffy/t.go": "package taffy\n"},
		},
		{
			name:    "root imports purego",
			files:   map[string]string{"root.go": "package x\n\nimport _ \"github.com/ebitengine/purego\"\n"},
			wantMsg: "root package imports github.com/ebitengine/purego",
		},
		{
			name:    "cgo outside render",
			files:   map[string]string{"other/c.go": "package other\n\nimport \"C\"\n"},
			wantMsg: `cgo ("C") is only allowed`,
		},
		{
			name:  "cgo under render/wgpu",
			files: map[string]string{"render/wgpu/c.go": "package wgpu\n\nimport \"C\"\n"},
		},
		{
			name: "linux package imports internal/linux",
			files: map[string]string{
				"platform/linux/x_linux.go": strings.Replace(pkg, "%s", "internal/linux/wl", 1),
				"internal/linux/wl/wl.go":   "//go:build linux\n\npackage wl\n",
			},
		},
		{
			name: "unconstrained package imports internal/linux",
			files: map[string]string{
				"platform/any/any.go":     strings.Replace(pkg, "%s", "internal/linux/wl", 1),
				"internal/linux/wl/wl.go": "//go:build linux\n\npackage wl\n",
			},
			wantMsg: "internal/linux/wl is imported only from packages built for",
		},
		{
			name: "windows package imports internal/apple",
			files: map[string]string{
				"platform/macos/m.go":           "//go:build darwin && !ios\n\n" + strings.Replace(pkg, "%s", "internal/apple/objc", 1),
				"platform/windows/w_windows.go": strings.Replace(pkg, "%s", "internal/apple/objc", 1),
				"internal/apple/objc/o.go":      "//go:build darwin || ios\n\npackage objc\n",
			},
			wantMsg: "internal/apple/objc is imported only from packages built for",
		},
		{
			name: "platform/macos may import internal/apple",
			files: map[string]string{
				"platform/macos/m.go":      "//go:build darwin && !ios\n\n" + strings.Replace(pkg, "%s", "internal/apple/objc", 1),
				"internal/apple/objc/o.go": "//go:build darwin || ios\n\npackage objc\n",
			},
		},
		{
			name:    "runtime.LockOSThread outside platform",
			files:   map[string]string{"root.go": "package x\n\nimport \"runtime\"\n\nfunc f() { runtime.LockOSThread() }\n"},
			wantMsg: "runtime.LockOSThread is called only from package platform",
		},
		{
			name:  "runtime.LockOSThread in platform",
			files: map[string]string{"platform/p.go": "package platform\n\nimport \"runtime\"\n\nfunc init() { runtime.LockOSThread() }\n"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			probs := lintTree(t, tt.files)
			if tt.wantMsg == "" {
				if len(probs) != 0 {
					t.Fatalf("unexpected: %v", probs)
				}
				return
			}
			if !hasProblem(probs, tt.wantMsg) {
				t.Fatalf("want %q, got %v", tt.wantMsg, probs)
			}
		})
	}
}

func TestLint_Comments(t *testing.T) {
	tests := []struct {
		name    string
		src     string
		wantBad int
	}{
		{"godoc on exported", "package x\n\n// Foo does a thing.\nfunc Foo() {}\n", 0},
		{"directive", "package x\n\n//go:noinline\nfunc f() {}\n", 0},
		{"gpui directive", "package x\n\n//gpui:action\ntype A struct{}\n", 0},
		{"generated header", "// Code generated by tool; DO NOT EDIT.\n\npackage x\n", 0},
		{"doc on unexported", "package x\n\n// f does a thing.\nfunc f() {}\n", 1},
		{"inline comment", "package x\n\nfunc f() {\n\t// why\n\t_ = 1\n}\n", 1},
		{"package doc", "// Package x is documented.\npackage x\n", 0},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			probs := lintTree(t, map[string]string{"x/x.go": tt.src})
			var n int
			for _, p := range probs {
				if strings.Contains(p.Msg, "comment not allowed") {
					n++
				}
			}
			if n != tt.wantBad {
				t.Fatalf("want %d comment problems, got %v", tt.wantBad, probs)
			}
		})
	}
}

func TestLint_MixinShadowing(t *testing.T) {
	src := `package x

type Styled[S any] struct{}

type Div struct {
	Styled[Div]
}

func (d *Div) W0p5() {}

type Span struct{}

func (s *Span) W0p5() {}
`
	probs := lintTree(t, map[string]string{"x/x.go": src})
	if !hasProblem(probs, "Div declares W0p5") {
		t.Fatalf("want shadowing problem, got %v", probs)
	}
	if hasProblem(probs, "Span") {
		t.Fatalf("type without mixin must not be flagged: %v", probs)
	}
}

func TestLint_DocsCaseCollision(t *testing.T) {
	probs := lintTree(t, map[string]string{"DOCS/readme.md": "x\n"})
	if !hasProblem(probs, "differs only by case from docs/") {
		t.Fatalf("want case problem, got %v", probs)
	}
}
