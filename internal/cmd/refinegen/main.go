// Command refinegen expands //gpui:refineable struct directives (upstream #[derive(Refineable)]) into <file>_gen.go.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"reflect"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

const (
	directive   = "//gpui:refineable"
	header      = "// Code generated by refinegen; DO NOT EDIT."
	gpuiutilPkg = "github.com/megascan/gpui-go/gpuiutil"
	refinePkg   = "github.com/megascan/gpui-go/refineable"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "refinegen:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	files := args
	if len(files) == 0 {
		entries, err := os.ReadDir(".")
		if err != nil {
			return err
		}
		for _, e := range entries {
			n := e.Name()
			if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || strings.HasSuffix(n, "_gen.go") {
				continue
			}
			files = append(files, n)
		}
	}
	for _, name := range files {
		src, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		out, err := Generate(name, src)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if out == nil {
			continue
		}
		target := strings.TrimSuffix(name, ".go") + "_gen.go"
		if err := os.WriteFile(target, out, 0o644); err != nil {
			return err
		}
	}
	return nil
}

type options struct {
	debug     bool
	partialEq bool
	serialize bool
}

type field struct {
	name       string
	typ        ast.Expr
	refineable bool
	optional   bool
	jsonName   string
}

type gen struct {
	fset     *token.FileSet
	file     *ast.File
	imports  map[string]string
	used     map[string]bool
	optQual  string
	b        bytes.Buffer
	needsRef bool
}

// Generate returns the generated file for src, or nil when src has no //gpui:refineable struct.
func Generate(filename string, src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	g := &gen{fset: fset, file: file, imports: map[string]string{}, used: map[string]bool{}}
	for _, imp := range file.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := p[strings.LastIndexByte(p, '/')+1:]
		if imp.Name != nil {
			name = imp.Name.Name
		}
		g.imports[name] = p
	}
	g.optQual = "gpuiutil."
	if file.Name.Name == "gpuiutil" {
		g.optQual = ""
	} else {
		g.used["gpuiutil"] = true
		g.imports["gpuiutil"] = gpuiutilPkg
	}
	count := 0
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts := spec.(*ast.TypeSpec)
			doc := ts.Doc
			if doc == nil && len(gd.Specs) == 1 {
				doc = gd.Doc
			}
			args, ok := findDirective(doc)
			if !ok {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return nil, errors.New("This derive macro only supports structs with named fields")
			}
			if err := g.emitStruct(ts, st, parseOptions(args)); err != nil {
				return nil, err
			}
			count++
		}
	}
	if count == 0 {
		return nil, nil
	}
	return g.finish()
}

func findDirective(cg *ast.CommentGroup) ([]string, bool) {
	if cg == nil {
		return nil, false
	}
	for _, c := range cg.List {
		if c.Text == directive {
			return nil, true
		}
		if rest, ok := strings.CutPrefix(c.Text, directive+" "); ok {
			return strings.FieldsFunc(rest, func(r rune) bool { return r == ',' || unicode.IsSpace(r) }), true
		}
	}
	return nil, false
}

func parseOptions(args []string) options {
	var o options
	for _, a := range args {
		switch a {
		case "Debug":
			o.debug = true
		case "PartialEq":
			o.partialEq = true
		case "Serialize":
			o.serialize = true
		}
	}
	return o
}

func (g *gen) expr(e ast.Expr) string {
	ast.Inspect(e, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				g.used[id.Name] = true
			}
		}
		return true
	})
	var b bytes.Buffer
	_ = printer.Fprint(&b, g.fset, e)
	return b.String()
}

func isOptional(e ast.Expr) bool {
	var x ast.Expr
	switch t := e.(type) {
	case *ast.IndexExpr:
		x = t.X
	default:
		return false
	}
	switch t := x.(type) {
	case *ast.Ident:
		return t.Name == "Option"
	case *ast.SelectorExpr:
		return t.Sel.Name == "Option"
	}
	return false
}

func splitGeneric(e ast.Expr) (base ast.Expr, args []ast.Expr) {
	switch t := e.(type) {
	case *ast.IndexExpr:
		return t.X, []ast.Expr{t.Index}
	case *ast.IndexListExpr:
		return t.X, t.Indices
	}
	return e, nil
}

func (g *gen) nestedName(e ast.Expr, suffix string, keepRefinement bool) (string, error) {
	base, args := splitGeneric(e)
	var qual, name string
	switch t := base.(type) {
	case *ast.Ident:
		name = t.Name
	case *ast.SelectorExpr:
		id, ok := t.X.(*ast.Ident)
		if !ok {
			return "", errors.New("Expected struct type for a refineable field")
		}
		g.used[id.Name] = true
		qual, name = id.Name+".", t.Sel.Name
	default:
		return "", errors.New("Expected struct type for a refineable field")
	}
	if keepRefinement && strings.HasSuffix(name, "Refinement") {
		name = strings.TrimSuffix(name, "Refinement")
	}
	out := qual + name + suffix
	if len(args) > 0 {
		parts := make([]string, len(args))
		for i, a := range args {
			parts[i] = g.expr(a)
		}
		out += "[" + strings.Join(parts, ", ") + "]"
	}
	return out, nil
}

func (g *gen) wrapperType(f field) (string, error) {
	switch {
	case f.refineable:
		return g.nestedName(f.typ, "Refinement", true)
	case f.optional:
		return g.expr(f.typ), nil
	}
	return g.optQual + "Option[" + g.expr(f.typ) + "]", nil
}

func snakeCase(s string) string {
	r := []rune(s)
	var b strings.Builder
	for i, c := range r {
		if unicode.IsUpper(c) {
			if i > 0 && (unicode.IsLower(r[i-1]) || unicode.IsDigit(r[i-1]) ||
				(i+1 < len(r) && unicode.IsLower(r[i+1]) && unicode.IsUpper(r[i-1]))) {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(c))
			continue
		}
		b.WriteRune(c)
	}
	return b.String()
}

func jsonName(goName string, tag *ast.BasicLit) string {
	if tag != nil {
		raw, err := strconv.Unquote(tag.Value)
		if err == nil {
			if v, ok := reflect.StructTag(raw).Lookup("json"); ok {
				if n, _, _ := strings.Cut(v, ","); n != "" && n != "-" {
					return n
				}
			}
		}
	}
	return snakeCase(goName)
}

func (g *gen) p(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

func (g *gen) emitStruct(ts *ast.TypeSpec, st *ast.StructType, opt options) error {
	ident := ts.Name.Name
	refinement := ident + "Refinement"
	var tparams, targs string
	if ts.TypeParams != nil && len(ts.TypeParams.List) > 0 {
		var decl, names []string
		for _, f := range ts.TypeParams.List {
			c := g.expr(f.Type)
			for _, n := range f.Names {
				names = append(names, n.Name)
			}
			ns := make([]string, len(f.Names))
			for i, n := range f.Names {
				ns[i] = n.Name
			}
			decl = append(decl, strings.Join(ns, ", ")+" "+c)
		}
		tparams = "[" + strings.Join(decl, ", ") + "]"
		targs = "[" + strings.Join(names, ", ") + "]"
	}
	var fields []field
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			return errors.New("This derive macro only supports structs with named fields")
		}
		_, nested := findDirective(f.Doc)
		if !nested {
			_, nested = findDirective(f.Comment)
		}
		for _, n := range f.Names {
			fields = append(fields, field{
				name:       n.Name,
				typ:        f.Type,
				refineable: nested,
				optional:   isOptional(f.Type),
				jsonName:   jsonName(n.Name, f.Tag),
			})
		}
	}
	self := ident + targs
	ref := refinement + targs

	g.p("// %s is a refinable version of %s, see that documentation for details.", refinement, ident)
	g.p("type %s%s struct {", refinement, tparams)
	for _, f := range fields {
		w, err := g.wrapperType(f)
		if err != nil {
			return err
		}
		tag := ""
		if opt.serialize {
			tag = fmt.Sprintf(" `json:\"%s,omitzero\"`", f.jsonName)
		}
		g.p("\t%s %s%s", f.name, w, tag)
	}
	g.p("}\n")

	g.p("// Refine applies the Some values of refinement to s.")
	g.p("func (s *%s) Refine(refinement *%s) {", self, ref)
	for _, f := range fields {
		switch {
		case f.refineable:
			g.p("\ts.%s.Refine(&refinement.%s)", f.name, f.name)
		case f.optional:
			g.p("\tif refinement.%s.IsSome() {\n\t\ts.%s = refinement.%s\n\t}", f.name, f.name, f.name)
		default:
			g.p("\tif value, ok := refinement.%s.Get(); ok {\n\t\ts.%s = value\n\t}", f.name, f.name)
		}
	}
	g.p("}\n")

	g.p("// Refined returns s with refinement applied.")
	g.p("func (s %s) Refined(refinement %s) %s {", self, ref, self)
	for _, f := range fields {
		switch {
		case f.refineable:
			g.p("\ts.%s = s.%s.Refined(refinement.%s)", f.name, f.name, f.name)
		case f.optional:
			g.p("\tif refinement.%s.IsSome() {\n\t\ts.%s = refinement.%s\n\t}", f.name, f.name, f.name)
		default:
			g.p("\tif value, ok := refinement.%s.Get(); ok {\n\t\ts.%s = value\n\t}", f.name, f.name)
		}
	}
	g.p("\treturn s\n}\n")

	g.needsRef = true
	g.p("// IsSupersetOf reports whether s already holds every value refinement sets.")
	g.p("func (s %s) IsSupersetOf(refinement *%s) bool {", self, ref)
	for _, f := range fields {
		switch {
		case f.refineable:
			g.p("\tif !s.%s.IsSupersetOf(&refinement.%s) {\n\t\treturn false\n\t}", f.name, f.name)
		case f.optional:
			g.p("\tif refinement.%s.IsSome() && !refineable.OptionEq(s.%s, refinement.%s) {\n\t\treturn false\n\t}", f.name, f.name, f.name)
		default:
			g.p("\tif refinementValue, ok := refinement.%s.Get(); ok && !refineable.Eq(s.%s, refinementValue) {\n\t\treturn false\n\t}", f.name, f.name)
		}
	}
	g.p("\treturn true\n}\n")

	g.p("// Subtract returns the values of s that refinement does not already hold.")
	g.p("func (s %s) Subtract(refinement *%s) %s {", self, ref, ref)
	g.p("\tvar out %s", ref)
	for _, f := range fields {
		switch {
		case f.refineable:
			g.p("\tout.%s = s.%s.Subtract(&refinement.%s)", f.name, f.name, f.name)
		case f.optional:
			g.p("\tif !refineable.OptionEq(s.%s, refinement.%s) {\n\t\tout.%s = s.%s\n\t}", f.name, f.name, f.name, f.name)
		default:
			g.p("\tif refinementValue, ok := refinement.%s.Get(); !ok || !refineable.Eq(s.%s, refinementValue) {\n\t\tout.%s = %sSome(s.%s)\n\t}", f.name, f.name, f.name, g.optQual, f.name)
		}
	}
	g.p("\treturn out\n}\n")

	g.p("// Refine applies the Some values of refinement to r.")
	g.p("func (r *%s) Refine(refinement *%s) {", ref, ref)
	for _, f := range fields {
		if f.refineable {
			g.p("\tr.%s.Refine(&refinement.%s)", f.name, f.name)
		} else {
			g.p("\tif refinement.%s.IsSome() {\n\t\tr.%s = refinement.%s\n\t}", f.name, f.name, f.name)
		}
	}
	g.p("}\n")

	g.p("// Refined returns r with refinement applied.")
	g.p("func (r %s) Refined(refinement %s) %s {", ref, ref, ref)
	for _, f := range fields {
		if f.refineable {
			g.p("\tr.%s = r.%s.Refined(refinement.%s)", f.name, f.name, f.name)
		} else {
			g.p("\tif refinement.%s.IsSome() {\n\t\tr.%s = refinement.%s\n\t}", f.name, f.name, f.name)
		}
	}
	g.p("\treturn r\n}\n")

	g.p("// IsSupersetOf reports whether r already holds every value refinement sets.")
	g.p("func (r %s) IsSupersetOf(refinement *%s) bool {", ref, ref)
	for _, f := range fields {
		if f.refineable {
			g.p("\tif !r.%s.IsSupersetOf(&refinement.%s) {\n\t\treturn false\n\t}", f.name, f.name)
		} else {
			g.p("\tif refinement.%s.IsSome() && !refineable.OptionEq(r.%s, refinement.%s) {\n\t\treturn false\n\t}", f.name, f.name, f.name)
		}
	}
	g.p("\treturn true\n}\n")

	g.p("// Subtract returns the values of r that refinement does not already hold.")
	g.p("func (r %s) Subtract(refinement *%s) %s {", ref, ref, ref)
	g.p("\tvar out %s", ref)
	for _, f := range fields {
		if f.refineable {
			g.p("\tout.%s = r.%s.Subtract(&refinement.%s)", f.name, f.name, f.name)
		} else {
			g.p("\tif !refineable.OptionEq(r.%s, refinement.%s) {\n\t\tout.%s = r.%s\n\t}", f.name, f.name, f.name, f.name)
		}
	}
	g.p("\treturn out\n}\n")

	g.p("// IsEmpty reports whether applying r would have no effect.")
	g.p("func (r %s) IsEmpty() bool {", ref)
	conds := make([]string, len(fields))
	for i, f := range fields {
		if f.refineable {
			conds[i] = "r." + f.name + ".IsEmpty()"
		} else {
			conds[i] = "r." + f.name + ".IsNone()"
		}
	}
	if len(conds) == 0 {
		conds = []string{"true"}
	}
	g.p("\treturn %s\n}\n", strings.Join(conds, " &&\n\t\t"))

	g.p("// %sFromRefinement converts a refinement into %s, using zero values for unset fields.", ident, ident)
	g.p("func %sFromRefinement%s(value %s) %s {", ident, tparams, ref, self)
	g.p("\treturn %s{", self)
	for _, f := range fields {
		switch {
		case f.refineable:
			if base, _ := splitGeneric(f.typ); strings.HasSuffix(baseIdent(base), "Refinement") {
				g.p("\t\t%s: value.%s,", f.name, f.name)
			} else {
				fn, err := g.nestedName(base, "FromRefinement", false)
				if err != nil {
					return err
				}
				g.p("\t\t%s: %s(value.%s),", f.name, fn, f.name)
			}
		case f.optional:
			g.p("\t\t%s: value.%s,", f.name, f.name)
		default:
			g.p("\t\t%s: value.%s.UnwrapOrDefault(),", f.name, f.name)
		}
	}
	g.p("\t}\n}\n")

	g.p("// IsSome reports whether any field of r is set.")
	g.p("func (r %s) IsSome() bool {", ref)
	for _, f := range fields {
		g.p("\tif r.%s.IsSome() {\n\t\treturn true\n\t}", f.name)
	}
	g.p("\treturn false\n}\n")

	if opt.partialEq {
		g.p("// Eq reports whether r and other set the same values.")
		g.p("func (r %s) Eq(other %s) bool {", ref, ref)
		for _, f := range fields {
			if f.refineable {
				g.p("\tif !refineable.Eq(r.%s, other.%s) {\n\t\treturn false\n\t}", f.name, f.name)
			} else {
				g.p("\tif !refineable.OptionEq(r.%s, other.%s) {\n\t\treturn false\n\t}", f.name, f.name)
			}
		}
		g.p("\treturn true\n}\n")
	}

	if opt.serialize {
		g.p("// IsZero reports whether r is empty, so `omitzero` skips it.")
		g.p("func (r %s) IsZero() bool {\n\treturn r.IsEmpty()\n}\n", ref)
	}

	if opt.debug {
		g.p("// String formats r like Rust's Debug, listing only the fields that are set.")
		g.p("func (r %s) String() string {", ref)
		g.p("\tdebugStruct := refineable.NewDebugStruct(%q)", refinement)
		g.p("\tallSome := true")
		for _, f := range fields {
			g.p("\tif r.%s.IsSome() {\n\t\tdebugStruct.Field(%q, r.%s)\n\t} else {\n\t\tallSome = false\n\t}", f.name, f.name, f.name)
		}
		g.p("\tif allSome {\n\t\treturn debugStruct.Finish()\n\t}\n\treturn debugStruct.FinishNonExhaustive()\n}\n")
	}
	return nil
}

func baseIdent(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return t.Sel.Name
	}
	return ""
}

func (g *gen) finish() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header + "\n\n")
	fmt.Fprintf(&out, "package %s\n\n", g.file.Name.Name)
	if g.needsRef {
		g.used["refineable"] = true
		if _, ok := g.imports["refineable"]; !ok {
			g.imports["refineable"] = refinePkg
		}
	}
	var lines []string
	for name := range g.used {
		p, ok := g.imports[name]
		if !ok {
			continue
		}
		base := p[strings.LastIndexByte(p, '/')+1:]
		if base == name {
			lines = append(lines, strconv.Quote(p))
		} else {
			lines = append(lines, name+" "+strconv.Quote(p))
		}
	}
	slices.SortFunc(lines, func(a, b string) int {
		return strings.Compare(importPath(a), importPath(b))
	})
	var std, other []string
	for _, l := range lines {
		first, _, _ := strings.Cut(strings.Trim(importPath(l), `"`), "/")
		if strings.Contains(first, ".") {
			other = append(other, l)
		} else {
			std = append(std, l)
		}
	}
	if len(lines) > 0 {
		out.WriteString("import (\n")
		for _, l := range std {
			out.WriteString("\t" + l + "\n")
		}
		if len(std) > 0 && len(other) > 0 {
			out.WriteString("\n")
		}
		for _, l := range other {
			out.WriteString("\t" + l + "\n")
		}
		out.WriteString(")\n\n")
	}
	out.Write(g.b.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w\n%s", err, out.Bytes())
	}
	return formatted, nil
}

func importPath(line string) string {
	if i := strings.IndexByte(line, '"'); i >= 0 {
		return line[i:]
	}
	return line
}
